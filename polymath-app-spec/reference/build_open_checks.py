#!/usr/bin/env python3
"""Build content/syllabi/skill-specs/OPEN-CHECKS.md: every flagged fact a reviewer must settle before `verified`."""
from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPECS = ROOT / "content" / "syllabi" / "skill-specs"
MARK = re.compile(r"(?-i:\bUNCERTAIN\b)|\[uncertain|\[P\b|\(snippet\)|unofficial mirror|(?<!built )(?<!answered )from memory(?!, draw)|not opened|(?<!can)not read\b|not confirmed|secondary source|unconfirmed|snippet only|could not (?!fail)", re.I)
KIND = [("Invented or project value", r"\[P\b"), ("Weak source", r"snippet|unofficial mirror|secondary source|not opened|(?<!can)not read\b"), ("Unconfirmed fact", r".")]


def walk(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, list):
        for item in value:
            yield from walk(item)


def main() -> None:
    lines = ["# Open checks, T1 to T6\n", "Generated by `reference/build_open_checks.py`. Settle these during human review, before a skill can become `verified`.\n"]
    total = 0
    for path in sorted(SPECS.glob("T[1-6]*.yaml")):
        rows = []
        for spec in yaml.safe_load(path.read_text(encoding="utf-8")):
            for field in ("core_ideas", "misconceptions", "worked_example", "unaided_check", "sources"):
                for text in walk(spec.get(field)):
                    for sentence in re.split(r"(?<=[.;])\s+", " ".join(text.split())):
                        if MARK.search(sentence):
                            kind = next(k for k, p in KIND if re.search(p, sentence, re.I))
                            rows.append(f"| `{spec['key']}` | {kind} | {sentence[:200].replace('|', '/')} |")
        lines += [f"\n## {path.stem} ({len(rows)})\n", "| Skill | Type | Flag |", "|---|---|---|", *rows]
        total += len(rows)
    lines.insert(2, f"Total flags: {total}.\n")
    (SPECS / "OPEN-CHECKS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(total)


if __name__ == "__main__":
    main()
